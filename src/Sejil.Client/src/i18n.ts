export const locale = typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en';
export const dictionary: Dictionary = locale === 'fr' ? fr : en;

type Key = { [K in keyof Dictionary]: Dictionary[K] extends string ? K : never }[keyof Dictionary];

/** Texte traduit; `{x}` est remplacé par `params.x`, et « a | b » choisit le singulier (n = 1) ou le pluriel. */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  let text = dictionary[key] as string;
  if (text.includes(' | ')) {
    const [one, many] = text.split(' | ');
    text = Number(params.n) === 1 || Number(params.n) === 0 && locale === 'fr' ? one : many;
  }
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}
